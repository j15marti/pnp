#!/usr/bin/env python3
"""Verify an exact UNSAT-supported order-3 fractional-design certificate.

Certificate format is the gzip-compressed JSON emitted by the TASK-008
experimental workflow.  The verifier checks:
1. support syntax and exact weight;
2. all rational weights are strictly positive and sum exactly to one;
3. every support formula is UNSAT by independent bit-parallel exhaustive truth table;
4. every canonical order-three orbit equation holds exactly over the integers.

It intentionally does not regenerate the uniform target counts.  Those are
independently regenerated by fractional_design3_exact.py in bounded chunks.

Designed to finish in roughly <30 seconds for q=16 or q=18 certificates.
"""

from __future__ import annotations

import argparse
import gzip
import itertools
import json
import math
import time
from collections import Counter

import numpy as np

PERMS = list(itertools.permutations(range(3)))
TRANS = {}
for a in (-1, 0, 1):
    for b in (-1, 0, 1):
        for c in (-1, 0, 1):
            if a == b == c == 0:
                continue
            v = (a, b, c)
            nv = tuple(-x for x in v)
            norm = min(v, nv)
            TRANS[v] = (norm[0] + 1) * 9 + (norm[1] + 1) * 3 + (norm[2] + 1)

PERM_CODE = {
    v: [TRANS[(v[p[0]], v[p[1]], v[p[2]])] for p in PERMS]
    for v in TRANS
}


def canonical_triple(c1, c2, c3):
    incidence = {}
    for j, clause in enumerate((c1, c2, c3)):
        for lit in clause:
            var = abs(lit)
            sign = 1 if lit > 0 else -1
            arr = incidence.setdefault(var, [0, 0, 0])
            arr[j] = sign

    permuted = [[] for _ in range(6)]
    for arr in incidence.values():
        codes = PERM_CODE[tuple(arr)]
        for i, code in enumerate(codes):
            permuted[i].append(code)
    return min(tuple(sorted(x)) for x in permuted)


def exact_counts(formula):
    counts = Counter()
    for i, j, k in itertools.combinations(range(len(formula)), 3):
        counts[canonical_triple(formula[i], formula[j], formula[k])] += 1
    return counts


def brute_force_unsat(formulas, q):
    nassign = 1 << q
    assignments = np.arange(nassign, dtype=np.uint32)
    allmask = (1 << nassign) - 1

    litmask = {}
    for v in range(1, q + 1):
        bits = ((assignments >> (v - 1)) & 1).astype(np.uint8)
        packed = np.packbits(bits, bitorder="little")
        mask = int.from_bytes(packed.tobytes(), "little")
        litmask[v] = mask
        litmask[-v] = allmask ^ mask

    for formula in formulas:
        mask = allmask
        for clause in formula:
            mask &= litmask[clause[0]] | litmask[clause[1]] | litmask[clause[2]]
            if mask == 0:
                break
        if mask != 0:
            return False
    return True


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("certificate")
    args = ap.parse_args()

    start = time.time()
    with gzip.open(args.certificate, "rt", encoding="utf-8") as fh:
        cert = json.load(fh)

    q = int(cert["q"])
    t = int(cert["t"])
    den = int(cert["denominator"])
    nums = [int(x) for x in cert["weights_numerators"]]
    formulas = [
        tuple(tuple(int(lit) for lit in clause) for clause in formula)
        for formula in cert["support_formulas"]
    ]
    orbit_keys = [tuple(int(x) for x in key) for key in cert["orbit_keys"]]
    target_counts = [int(x) for x in cert["target_counts"]]
    target_den = int(cert["target_pair_denominator"])
    triple_den = int(cert["triple_count_per_formula"])

    assert len(nums) == len(formulas) == 84
    assert all(x > 0 for x in nums)
    assert sum(nums) == den

    for formula in formulas:
        assert len(formula) == t
        assert len(set(formula)) == t
        for clause in formula:
            assert len(clause) == 3
            assert len({abs(x) for x in clause}) == 3
            assert all(1 <= abs(x) <= q for x in clause)

    assert brute_force_unsat(formulas, q)

    counts = [exact_counts(formula) for formula in formulas]
    for j, key in enumerate(orbit_keys):
        lhs = sum(
            nums[i] * counts[i].get(key, 0) * target_den
            for i in range(84)
        )
        rhs = den * target_counts[j] * triple_den
        assert lhs == rhs

    print(json.dumps({
        "verified": True,
        "q": q,
        "t": t,
        "support": 84,
        "all_weights_strictly_positive": True,
        "weights_sum_exactly_one": True,
        "all_support_formulas_unsat_by_exhaustive_truth_table": True,
        "all_orbit_equations_exact": True,
        "seconds": time.time() - start,
    }, sort_keys=True))


if __name__ == "__main__":
    main()
