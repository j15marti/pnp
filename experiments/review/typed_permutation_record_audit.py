#!/usr/bin/env python3
"""Independent strict-record audit for CHECKABLEPERM1.

Finds the smallest omitted malformed controls in PERMEXT1's first recognizer,
then checks a repaired purely syntactic recognizer and the Gold-cube witness
map.  No finite result is interpreted as an asymptotic lower bound.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import time
from dataclasses import replace
from pathlib import Path

import permutation_residual_unique_extension_audit as base


def strict_recognize(d: int, modulus: int, g: base.Graph, target_bits: int) -> bool:
    if d < 3 or d % 2 == 0 or target_bits != d:
        return False
    if not base.is_irreducible(modulus, d):
        return False
    if g.vertices < 1:
        return False
    m = len(g.edges)
    if m - g.vertices + 1 != d:
        return False
    if any(a < 0 or b < 0 or a >= g.vertices or b >= g.vertices or a == b
           for a, b in g.edges):
        return False
    canonical_edges = [tuple(sorted(e)) for e in g.edges]
    if len(set(canonical_edges)) != m:
        return False
    if len(g.tree) != g.vertices - 1 or len(set(g.tree)) != len(g.tree):
        return False
    if len(g.cotree) != d or len(set(g.cotree)) != len(g.cotree):
        return False
    if any(i < 0 or i >= m for i in g.tree + g.cotree):
        return False
    if set(g.tree) & set(g.cotree):
        return False
    if set(g.tree) | set(g.cotree) != set(range(m)):
        return False
    # Verify the declared tree itself, rather than recomputing some tree.
    parent = list(range(g.vertices))

    def find(x: int) -> int:
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x

    for i in g.tree:
        a, b = g.edges[i]
        ra, rb = find(a), find(b)
        if ra == rb:
            return False
        parent[ra] = rb
    return len({find(v) for v in range(g.vertices)}) == 1


def run() -> dict:
    start = time.perf_counter()
    assertions = 0
    failures: list[str] = []
    valid_witnesses = 0

    for d in (3, 5, 7, 9):
        modulus = base.first_irreducible(d)
        g = base.graph_for_rank(d)
        assertions += 2
        if not strict_recognize(d, modulus, g, d):
            failures.append(f"valid-rejected:{d}")
        if not base.recognize_record(d, modulus, g, d):
            failures.append(f"legacy-valid-rejected:{d}")
        inv = ((1 << (d + 1)) - 1) // 3
        for u_raw in range(1 << min(6, d + 2)):
            u = base.bits(u_raw, min(6, d + 2))
            b = base.source_target(u, d, 1)
            z = base.gf_pow(b, inv, modulus, d)
            charge = base.source_charge(u, g.vertices, 1)
            x = base.lift(g, charge, z)
            assertions += 3
            valid_witnesses += 1
            if not base.incidence_ok(g, x, charge):
                failures.append(f"incidence:{d}:{u_raw}")
            if base.cotree_value(g, x) != z:
                failures.append(f"cotree:{d}:{u_raw}")
            if base.gf_pow(z, 3, modulus, d) != b:
                failures.append(f"residual:{d}:{u_raw}")

    # The d=3 graph is the smallest graph used by PERMEXT1.  Its legacy
    # recognizer checks that the graph has some spanning tree, but not that the
    # declared tree/cotree is the promised partition.
    d = 3
    modulus = base.first_irreducible(d)
    g = base.graph_for_rank(d)
    malformed = {
        "duplicate_tree_index": replace(g, tree=(g.tree[0],) + g.tree[:-1]),
        "tree_index_out_of_range": replace(g, tree=g.tree[:-1] + (len(g.edges),)),
        "missing_cotree_index": replace(g, cotree=g.cotree[:-1]),
        "duplicate_cotree_index": replace(g, cotree=(g.cotree[0],) + g.cotree[:-1]),
        "tree_cotree_overlap": replace(g, cotree=(g.tree[0],) + g.cotree[1:]),
        "loop_edge": replace(g, edges=((0, 0),) + g.edges[1:]),
        "duplicate_edge": replace(g, edges=(g.edges[0], g.edges[0]) + g.edges[2:]),
        "bad_endpoint": replace(g, edges=((0, g.vertices),) + g.edges[1:]),
    }
    legacy_false_accepts = []
    legacy_crashes = []
    for name, bad in malformed.items():
        try:
            old_accepts = base.recognize_record(d, modulus, bad, d)
        except (IndexError, ValueError):
            old_accepts = False
            legacy_crashes.append(name)
        new_accepts = strict_recognize(d, modulus, bad, d)
        assertions += 2
        if old_accepts:
            legacy_false_accepts.append(name)
        if new_accepts:
            failures.append(f"strict-false-accept:{name}")

    # Parity is generated by syntax: last bit is XOR of prior bits.
    parity_cases = 0
    for vertices in range(2, 34):
        for mask in range(1 << min(vertices - 1, 10)):
            first = base.bits(mask, min(vertices - 1, 10))
            first += [0] * (vertices - 1 - len(first))
            charge = first + [sum(first) & 1]
            assertions += 1
            parity_cases += 1
            if sum(charge) & 1:
                failures.append(f"parity:{vertices}:{mask}")

    elapsed = time.perf_counter() - start
    result = {
        "run_id": "CHECKABLEPERM1",
        "status": "PASS" if not failures else "FAIL",
        "assertions": assertions,
        "failures": failures,
        "valid_witnesses": valid_witnesses,
        "parity_cases": parity_cases,
        "malformed_records": len(malformed),
        "legacy_false_accepts": legacy_false_accepts,
        "legacy_crashes": legacy_crashes,
        "elapsed_seconds": elapsed,
        "method": "exhaustive finite fields/assignments plus deterministic malformed mutations",
        "limitations": [
            "finite checks support but do not prove the symbolic recognizer theorem",
            "the family is a transparent compiler image, not an unrestricted SAT lower bound",
            "arbitrary declared permutation/inverse circuits remain a semantic promise",
        ],
    }
    if failures:
        raise AssertionError(failures[:10])
    return result


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--output", required=True)
    args = ap.parse_args()
    result = run()
    result["code_sha256"] = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()
    out = Path(args.output)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(result, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print(json.dumps(result, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
