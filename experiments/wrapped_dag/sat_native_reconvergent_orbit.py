#!/usr/bin/env python3
"""
SAT-native reconvergent wrapper control.

A family of satisfiable CNFs is generated by signed variable renamings of one
base formula.  Every diamond:
  1. asks an actual restricted-SAT question on the current formula;
  2. branches on that SAT bit;
  3. applies one of two satisfiability-preserving signed renamings;
  4. reconverges at the same nominal control node.

Delayed re-separation is measured only with later SAT restriction queries.

Finite computational diagnostic only.  This does not prove a lower bound.
"""

import itertools
import json
import math
import random
import statistics
from functools import lru_cache


def planted_cnf(n, m, width, seed, family="random"):
    rng = random.Random(seed)
    planted = [rng.randrange(2) for _ in range(n)]
    clauses = []

    if family == "horn":
        planted = [0] * n
        while len(clauses) < m:
            vs = rng.sample(range(n), width)
            pos = rng.choice([-1] + list(range(width)))
            clauses.append(tuple(
                (v + 1) if j == pos else -(v + 1)
                for j, v in enumerate(vs)
            ))
        return clauses

    while len(clauses) < m:
        if family == "path":
            i = rng.randrange(max(1, n - width + 1))
            vs = list(range(i, i + width))
        else:
            vs = rng.sample(range(n), width)

        lits = [
            (v + 1) if rng.randrange(2) else -(v + 1)
            for v in vs
        ]

        def lit_value(lit):
            v = abs(lit) - 1
            bit = planted[v]
            return bit if lit > 0 else 1 - bit

        if not any(lit_value(lit) for lit in lits):
            lits[0] *= -1
        clauses.append(tuple(lits))

    return clauses


def xor3_to_cnf(vs, rhs):
    out = []
    for bits in itertools.product([0, 1], repeat=3):
        if bits[0] ^ bits[1] ^ bits[2] != rhs:
            out.append(tuple(
                (v + 1) if b == 0 else -(v + 1)
                for v, b in zip(vs, bits)
            ))
    return out


def xor_cnf(n, equations, seed):
    rng = random.Random(seed)
    planted = [rng.randrange(2) for _ in range(n)]
    clauses = []
    for _ in range(equations):
        vs = tuple(rng.sample(range(n), 3))
        rhs = planted[vs[0]] ^ planted[vs[1]] ^ planted[vs[2]]
        clauses.extend(xor3_to_cnf(vs, rhs))
    return clauses


def truth_table(n, clauses):
    tt = 0
    for a in range(1 << n):
        ok = True
        for clause in clauses:
            if not any(
                (((a >> (abs(lit) - 1)) & 1) == 1)
                if lit > 0
                else (((a >> (abs(lit) - 1)) & 1) == 0)
                for lit in clause
            ):
                ok = False
                break
        if ok:
            tt |= 1 << a
    return tt


def random_signed_perm(n, rng):
    p = list(range(n))
    rng.shuffle(p)
    return tuple(p), tuple(rng.randrange(2) for _ in range(n))


def compose(state, transition):
    p, f = state
    q, g = transition
    n = len(p)
    return (
        tuple(p[q[j]] for j in range(n)),
        tuple(g[j] ^ f[q[j]] for j in range(n)),
    )


def transform_tt(tt, state, n):
    p, f = state
    out = 0
    for y in range(1 << n):
        x = 0
        for i in range(n):
            if ((y >> i) & 1) ^ f[i]:
                x |= 1 << p[i]
        if (tt >> x) & 1:
            out |= 1 << y
    return out


def restriction_masks(n, k):
    masks = []
    for vs in itertools.combinations(range(n), k):
        for bits in itertools.product([0, 1], repeat=k):
            mask = 0
            for y in range(1 << n):
                if all(((y >> v) & 1) == b for v, b in zip(vs, bits)):
                    mask |= 1 << y
            masks.append(mask)
    return masks


def sat_signature(tt, masks):
    sig = 0
    for i, mask in enumerate(masks):
        if tt & mask:
            sig |= 1 << i
    return sig


@lru_cache(None)
def obdd_nodes(tt, n):
    unique = {}

    def rec(level, vals):
        if all(v == vals[0] for v in vals):
            return vals[0]
        low = vals[0::2]
        high = vals[1::2]
        lo = rec(level + 1, low)
        hi = rec(level + 1, high)
        if lo == hi:
            return lo
        key = (level, lo, hi)
        if key not in unique:
            unique[key] = len(unique) + 2
        return unique[key]

    vals = tuple((tt >> i) & 1 for i in range(1 << n))
    rec(0, vals)
    return len(unique)


def make_family(n, family, seed):
    if family == "3SAT":
        clauses = planted_cnf(n, 3 * n, 3, seed, "random")
    elif family == "2SAT":
        clauses = planted_cnf(n, 2 * n, 2, seed, "random")
    elif family == "Horn":
        clauses = planted_cnf(n, 2 * n, 3, seed, "horn")
    elif family == "Path":
        clauses = planted_cnf(n, 2 * n, 3, seed, "path")
    elif family == "XOR":
        clauses = xor_cnf(n, n // 2, seed)
    else:
        raise ValueError(family)
    return clauses, truth_table(n, clauses)


def branch_masks(n, depth, seed, fixed=3):
    rng = random.Random(seed)
    out = []
    for _ in range(depth):
        vs = rng.sample(range(n), fixed)
        bits = [rng.randrange(2) for _ in vs]
        mask = 0
        for y in range(1 << n):
            if all(((y >> v) & 1) == b for v, b in zip(vs, bits)):
                mask |= 1 << y
        out.append(mask)
    return out


def run_case(family, n=8, inputs=512, depth=10, seed=7):
    clauses, base_tt = make_family(n, family, seed)

    rng = random.Random(seed + 101)
    states = set()
    while len(states) < inputs:
        states.add(random_signed_perm(n, rng))
    states = list(states)

    transition_rng = random.Random(seed + 303)
    transitions = [
        [
            random_signed_perm(n, transition_rng),
            random_signed_perm(n, transition_rng),
        ]
        for _ in range(depth)
    ]

    branch = branch_masks(n, depth, seed + 202, fixed=3)
    q1 = restriction_masks(n, 1)
    q2 = restriction_masks(n, 2)
    q3 = restriction_masks(n, 3)

    histories = [0] * inputs
    tt_cache = {}
    rows = []

    for d in range(depth + 1):
        tables = []
        for state in states:
            if state not in tt_cache:
                tt_cache[state] = transform_tt(base_tt, state, n)
            tables.append(tt_cache[state])

        unique_tables = set(tables)
        obdd = [obdd_nodes(tt, n) for tt in unique_tables]

        rows.append({
            "depth": d,
            "branch_history_classes": len(set(histories)),
            "hidden_signed_permutation_states": len(set(states)),
            "one_literal_restriction_classes": len({
                sat_signature(tt, q1) for tt in unique_tables
            }),
            "two_literal_restriction_classes": len({
                sat_signature(tt, q2) for tt in unique_tables
            }),
            "three_literal_restriction_classes": len({
                sat_signature(tt, q3) for tt in unique_tables
            }),
            "full_boolean_function_classes": len(unique_tables),
            "fixed_order_obdd_nodes_min": min(obdd),
            "fixed_order_obdd_nodes_median": statistics.median(obdd),
            "fixed_order_obdd_nodes_max": max(obdd),
        })

        if d == depth:
            break

        next_states = []
        next_histories = []
        mask = branch[d]

        for state, history, tt in zip(states, histories, tables):
            sat_bit = 1 if (tt & mask) else 0
            next_states.append(compose(state, transitions[d][sat_bit]))
            next_histories.append((history << 1) | sat_bit)

        states = next_states
        histories = next_histories

    return {
        "family": family,
        "n": n,
        "input_orbit_samples": inputs,
        "depth": depth,
        "clauses": len(clauses),
        "satisfying_assignments": base_tt.bit_count(),
        "signed_permutation_encoding_bits_upper": (
            math.ceil(math.log2(math.factorial(n))) + n
        ),
        "rows": rows,
    }


def main():
    result = {
        "status": "COMPUTATIONAL_EXACT_FINITE",
        "note": (
            "A/B branch bits are actual SAT answers to restrictions. "
            "Branch-dependent transformations are satisfiability-preserving "
            "signed variable renamings. Delayed re-separation uses only later "
            "SAT restriction queries."
        ),
        "cases": [
            run_case(family)
            for family in ["3SAT", "2SAT", "Horn", "Path", "XOR"]
        ],
    }
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
