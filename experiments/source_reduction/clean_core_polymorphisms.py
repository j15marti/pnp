#!/usr/bin/env python3
"""
CLEANCORE-POLY1.

Enumerate the finite relation language generated by eliminating one degree-2
outside mediator from the 7-state type-1-chain domain D={0,1}^3\{000}, and
test low-arity polymorphism signatures.

Key exact checks:
  * all 36 simple two-literal cross-chain clauses occur;
  * all 7^7 unary operations are tested on the binary sublanguage;
  * binary polymorphisms are reduced to a 42-variable 2-SAT instance;
  * ternary majority, Maltsev, WNU3, and cyclic identities are tested as
    operation-CSPs over the binary relation language by arc consistency;
  * random small 3-SAT instances are compared to the standard dual 7-state
    clause-variable encoding.

These are finite exhaustive computations.  NP-hardness of the ambient
constraint language is proved analytically in the companion report.
"""

import collections
import itertools
import json
import random
from collections import deque

D = [x for x in itertools.product([0,1], repeat=3) if any(x)]

def canon_clause(lits):
    s=set(lits)
    for v,c,n in tuple(s):
        if (v,c,not n) in s:
            return None
    vs=sorted({v for v,_,_ in s})
    mp={v:i for i,v in enumerate(vs)}
    return tuple(sorted((mp[v],c,n) for v,c,n in s))

def pair_terms(num_vars=4):
    out=[]
    for a,b in itertools.combinations(range(num_vars),2):
        for ca,cb in itertools.product(range(3), repeat=2):
            for na,nb in itertools.product([False,True], repeat=2):
                out.append(((a,ca,na),(b,cb,nb)))
    return out

def enumerate_language():
    ts=pair_terms(4)
    rels=set()
    for a in ts:
        for b in ts:
            c=canon_clause(a+b)
            if c is not None:
                rels.add(c)
    return sorted(rels,key=lambda c:(max(v for v,_,_ in c)+1,len(c),c))

def clause_true(cl, ass):
    return any((1-D[ass[v]][c] if n else D[ass[v]][c]) for v,c,n in cl)

def relation_set(cl):
    r=max(v for v,_,_ in cl)+1
    return {(a[0],a[1]) for a in itertools.product(range(7),repeat=2)
            if r==2 and clause_true(cl,a)}

def op_preserves_clause(cl,op,arity):
    r=max(v for v,_,_ in cl)+1
    per=[[] for _ in range(r)]
    for v,c,n in cl: per[v].append((c,n))
    masks={0}
    for lits in per:
        nxt=set()
        for args in itertools.product(range(7), repeat=arity):
            out=op(args)
            if out is None:
                return False
            so=D[out]
            if any((1-so[c] if n else so[c]) for c,n in lits):
                continue
            m=0
            for j,a in enumerate(args):
                st=D[a]
                if any((1-st[c] if n else st[c]) for c,n in lits):
                    m |= 1<<j
            for old in masks:
                nxt.add(old|m)
        masks=nxt
        if not masks:
            return True
    return ((1<<arity)-1) not in masks

def preserves_all(op,arity,rels):
    return all(op_preserves_clause(c,op,arity) for c in rels)

def unary_polymorphisms(binary_rels):
    good=[]
    for mapping in itertools.product(range(7),repeat=7):
        if preserves_all(lambda a,m=mapping:m[a[0]],1,binary_rels):
            good.append(mapping)
    return good

def binary_polymorphism_certificate(binary_rels):
    rsets=[relation_set(c) for c in binary_rels]
    allpairs={(a,b) for a in range(7) for b in range(7)}
    allowed=[[set(allpairs) for _ in range(49)] for __ in range(49)]
    for R in rsets:
        for a,c in R:
            for b,d in R:
                allowed[7*a+b][7*c+d].intersection_update(R)

    # Diagonal operation-table constraints force f(a,b) in {a,b}.
    conservative=True
    for a in range(7):
        for b in range(7):
            u=7*a+b
            dom={z for z in range(7) if (z,z) in allowed[u][u]}
            target={a} if a==b else {a,b}
            if dom!=target:
                conservative=False

    var={}
    pairs=[]
    for a in range(7):
        for b in range(7):
            if a!=b:
                var[7*a+b]=len(pairs)
                pairs.append((a,b))

    clauses=set()
    for u in range(49):
        a,b=divmod(u,7)
        U=[(None,a)] if a==b else [(0,a),(1,b)]
        for v in range(49):
            c,d=divmod(v,7)
            V=[(None,c)] if c==d else [(0,c),(1,d)]
            for bu,ou in U:
                for bv,ov in V:
                    if (ou,ov) in allowed[u][v]:
                        continue
                    if bu is None or bv is None:
                        raise AssertionError("unexpected unary restriction")
                    # Forbid xu=bu and xv=bv:
                    # (xu != bu) OR (xv != bv).
                    cl=tuple(sorted(((var[u],1-bu),(var[v],1-bv))))
                    clauses.add(cl)

    n=len(pairs)
    G=[set() for _ in range(2*n)]
    def node(v,val): return 2*v+val
    for (x,a),(y,b) in clauses:
        G[node(x,1-a)].add(node(y,b))
        G[node(y,1-b)].add(node(x,a))

    # Kosaraju SCC
    seen=set();order=[]
    def dfs(v):
        seen.add(v)
        for w in G[v]:
            if w not in seen: dfs(w)
        order.append(v)
    for v in range(2*n):
        if v not in seen: dfs(v)
    RG=[set() for _ in range(2*n)]
    for v in range(2*n):
        for w in G[v]: RG[w].add(v)
    comp=[-1]*(2*n)
    def rdfs(v,c):
        comp[v]=c
        for w in RG[v]:
            if comp[w]<0:rdfs(w,c)
    cc=0
    for v in reversed(order):
        if comp[v]<0:
            rdfs(v,cc);cc+=1

    patterns={(comp[2*i],comp[2*i+1]) for i in range(n)}
    unsat=any(comp[2*i]==comp[2*i+1] for i in range(n))
    # If exactly one common ordered component-pair occurs, all 42 choices are
    # logically tied together; the two satisfying assignments are the projections.
    exact_two=(not unsat and len(patterns)==1 and cc==2)
    return {
        "conservative_table_domains":conservative,
        "boolean_choice_variables":n,
        "unique_2sat_clauses":len(clauses),
        "implication_sccs":cc,
        "common_component_pair_count":len(patterns),
        "exactly_two_binary_polymorphisms":exact_two,
    }

def fingerprints(binary_rels):
    rsets=[relation_set(c) for c in binary_rels]
    fp=[[0]*7 for _ in range(7)]
    for i,R in enumerate(rsets):
        bit=1<<i
        for a,b in R:fp[a][b]|=bit
    return fp,(1<<len(rsets))-1

class UF:
    def __init__(self,n):self.p=list(range(n))
    def find(self,x):
        if self.p[x]!=x:self.p[x]=self.find(self.p[x])
        return self.p[x]
    def union(self,a,b):
        a,b=self.find(a),self.find(b)
        if a!=b:self.p[b]=a

def identity_majority(t,idx):
    return [],[(i,collections.Counter(x).most_common(1)[0][0])
               for x,i in idx.items()
               if collections.Counter(x).most_common(1)[0][1]>=2]

def identity_maltsev(t,idx):
    fix=[]
    for x in range(7):
        for y in range(7):
            fix += [(idx[(x,x,y)],y),(idx[(x,y,y)],x)]
    return [],fix

def identity_wnu3(t,idx):
    eq=[];fix=[]
    for x in range(7):
        fix.append((idx[(x,x,x)],x))
        for y in range(7):
            if x==y:continue
            a,b,c=idx[(y,x,x)],idx[(x,y,x)],idx[(x,x,y)]
            eq += [(a,b),(b,c)]
    return eq,fix

def identity_cyclic3(t,idx):
    eq=[];fix=[]
    for x,i in idx.items():
        a,b,c=x
        eq += [(i,idx[(b,c,a)]),(i,idx[(c,a,b)])]
    for x in range(7):fix.append((idx[(x,x,x)],x))
    return eq,fix

def ternary_identity_ac(binary_rels,identity):
    fp,ALL=fingerprints(binary_rels)
    tuples=list(itertools.product(range(7),repeat=3))
    idx={t:i for i,t in enumerate(tuples)}
    uf=UF(len(tuples))
    eq,fix=identity(tuples,idx)
    for a,b in eq:uf.union(a,b)
    fixed={}
    for i,v in fix:
        r=uf.find(i)
        if r in fixed and fixed[r]!=v:return False,0
        fixed[r]=v
    roots=sorted({uf.find(i) for i in range(len(tuples))})
    rid={r:i for i,r in enumerate(roots)}
    dom=[0x7f]*len(roots)
    for r,v in fixed.items():dom[rid[uf.find(r)]]=1<<v

    # Cache relation requirements and allowed output pairs.
    am_cache={}
    def allow(u,v):
        req=ALL
        for a,b in zip(u,v):req &= fp[a][b]
        if req not in am_cache:
            m=0
            for p in range(7):
                for q in range(7):
                    if fp[p][q]&req==req:m|=1<<(7*p+q)
            am_cache[req]=m
        return am_cache[req]

    cons={}
    for u in tuples:
        cu=rid[uf.find(idx[u])]
        for v in tuples:
            cv=rid[uf.find(idx[v])]
            a=allow(u,v)
            cons[(cu,cv)]=cons.get((cu,cv),(1<<49)-1)&a

    # Self constraints.
    for i in range(len(dom)):
        a=cons[(i,i)]
        nd=0
        for x in range(7):
            if (dom[i]>>x)&1 and (a>>(7*x+x))&1:nd|=1<<x
        dom[i]=nd
        if not nd:return False,len(roots)

    neigh=[set() for _ in dom]
    for i,j in cons:
        if i!=j:neigh[i].add(j)

    q=deque((i,j) for i in range(len(dom)) for j in neigh[i])
    while q:
        i,j=q.popleft()
        allowij=cons[(i,j)]
        nd=0
        for a in range(7):
            if not ((dom[i]>>a)&1):continue
            row=(allowij>>(7*a))&0x7f
            if row&dom[j]:nd|=1<<a
        if nd!=dom[i]:
            dom[i]=nd
            if not nd:return False,len(roots)
            for h in neigh[i]:
                if h!=j:q.append((h,i))
    # Arc consistency not proving inconsistency would require search.
    return True,len(roots)

def sat3(n,clauses):
    for a in itertools.product([0,1],repeat=n):
        if all(any((1-a[v] if neg else a[v]) for v,neg in C) for C in clauses):
            return True
    return False

def dual7_sat(clauses):
    occ=collections.defaultdict(list)
    for ci,C in enumerate(clauses):
        for j,(v,neg) in enumerate(C):occ[v].append((ci,j,neg))
    edges=[]
    for os in occ.values():
        for a,b in zip(os,os[1:]):
            c1,j1,n1=a;c2,j2,n2=b
            edges.append((c1,j1,c2,j2,n1==n2))
    for states in itertools.product(D,repeat=len(clauses)):
        if all((states[a][i]==states[b][j])==same for a,i,b,j,same in edges):
            return True
    return False

def main():
    rels=enumerate_language()
    by=collections.Counter(max(v for v,_,_ in c)+1 for c in rels)
    binary=[c for c in rels if max(v for v,_,_ in c)+1==2]

    simple=[]
    for i,j in itertools.product(range(3),repeat=2):
        for a,b in itertools.product([False,True],repeat=2):
            q=tuple(sorted(((0,i,a),(1,j,b))))
            if q in binary:simple.append(q)

    unary=unary_polymorphisms(binary)
    bcert=binary_polymorphism_certificate(binary)

    ternary={}
    for name,identity in [
        ("majority",identity_majority),
        ("maltsev",identity_maltsev),
        ("wnu3",identity_wnu3),
        ("cyclic3",identity_cyclic3),
    ]:
        ac_survives,classes=ternary_identity_ac(binary,identity)
        ternary[name]={
            "operation_table_equivalence_classes":classes,
            "arc_consistency_survives":ac_survives,
            "refuted_by_arc_consistency":not ac_survives,
        }

    rng=random.Random(20261005)
    checks=0
    for n in range(3,6):
        for _ in range(20):
            m=min(5,n+1)
            C=[]
            for __ in range(m):
                vs=rng.sample(range(n),3)
                C.append(tuple((v,bool(rng.randrange(2))) for v in vs))
            assert sat3(n,C)==dual7_sat(C)
            checks+=1

    result={
        "domain":D,
        "all_relation_schemas":len(rels),
        "arity_counts":dict(by),
        "binary_relation_schemas":len(binary),
        "simple_cross_chain_2literal_relations":len(simple),
        "all_36_simple_2literal_relations_present":len(simple)==36,
        "unary_polymorphism_count":len(unary),
        "unary_polymorphisms":unary,
        "binary_polymorphism_certificate":bcert,
        "ternary_identity_tests":ternary,
        "random_dual_encoding_equivalence_checks":checks,
        "all_random_dual_encoding_checks_passed":True,
    }
    print(json.dumps(result,indent=2))

if __name__=="__main__":
    main()
