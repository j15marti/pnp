#!/usr/bin/env python3
"""Independent no-producer-import directional cofactor verifier LSPV-1 320.
Expects result320.json generated by the full reproducibility producer in this directory.
"""
import json
from pathlib import Path
P9=((1,5,6),(2,3,8),(1,3,5),(4,6,9),(2,4,7),(7,8,9))
N9=((4,6,8),(1,6,7),(2,3,4),(3,5,8),(1,2,9),(5,7,9))
PY6=((1,2,3),(1,4,5),(2,4,6),(3,5,6))
NY6=((1,2,4),(1,3,6),(2,3,5),(4,5,6))
def records(p,n,offset=0):
    return [(tuple(q+offset for q in c),True) for c in p]+[(tuple(q+offset for q in c),False) for c in n]
def valid_at(formula,assignment):
    for clause,ispos in formula:
        if ispos:
            if not any((assignment>>(i-1))&1 for i in clause):return False
        else:
            if all((assignment>>(i-1))&1 for i in clause):return False
    return True
def main():
    d=json.loads(Path(__file__).with_name('result320.json').read_text());tests=0
    families={'F9':(9,records(P9,N9)),'Y6':(6,records(PY6,NY6)),'H15_disjoint':(15,records(P9,N9)+records(PY6,NY6,9))}
    for name,(n,clauses) in families.items():
        o=d['families'][name];assert o['n']==n and o['m']==len(clauses)
        accepted={a for a in range(1<<n) if valid_at(clauses,a)}
        assert len(accepted)==o['models'];tests+=1
        for pivot in range(1,n+1):
            count={v:0 for v in ('f0','f1','only0','only1','both','neither','T0a','T0b','T0overlap','T1a','T1b','T1overlap')}
            p=[set(c)-{pivot} for c,pos in clauses if pos and pivot in c]
            q=[set(c)-{pivot} for c,pos in clauses if not pos and pivot in c]
            assert len(p)==len(q)==2
            for mask in range(1<<n):
                if mask&(1<<(pivot-1)):continue
                pair=(mask,mask|(1<<(pivot-1)))
                yes=[q in accepted for q in pair]
                if yes[0]:count['f0']+=1
                if yes[1]:count['f1']+=1
                key=('both' if all(yes) else 'only0' if yes[0] else 'only1' if yes[1] else 'neither')
                count[key]+=1
                cond0=[yes[0] and all((mask>>(i-1))&1 for i in c) for c in q]
                cond1=[yes[1] and all(not ((mask>>(i-1))&1) for i in c) for c in p]
                assert any(cond0)==(key=='only0')
                assert any(cond1)==(key=='only1')
                count['T0a']+=cond0[0];count['T0b']+=cond0[1];count['T0overlap']+=all(cond0)
                count['T1a']+=cond1[0];count['T1b']+=cond1[1];count['T1overlap']+=all(cond1)
                tests+=3
            assert count==o['x'][str(pivot)]['counts'],(name,pivot,count,o['x'][str(pivot)]['counts'])
            tests+=len(count)
        for a in range(1<<n):
            anti=((1<<n)-1)^a
            for c,pos in clauses:
                s=sum((((a>>(i-1))&1)==int(pos)) for i in c)
                t=sum((((anti>>(i-1))&1)==int(pos)) for i in c)
                assert s+t==3;tests+=1
    b=d['F9_same_original_context']['branch']
    for val in ('0','1'):
        for a in b[val]['models']:
            assert valid_at(families['F9'][1],a) and bool(a&1)==bool(int(val));tests+=1
        for leaf in b[val]['falsification_leaves']:
            a=leaf['mask'];clause,pos=families['F9'][1][leaf['source_clause_0based']]
            assert not valid_at([(clause,pos)],a);tests+=1
    assert len(b['0']['models'])==2 and len(b['1']['falsification_leaves'])==8
    f9=d['families']['F9']['x']['1']['counts']
    assert f9['only0']==28 and f9['only1']==18 and f9['T0overlap']==2
    n15=d['families']['H15_disjoint']['x']['10']['counts']
    y6=d['families']['Y6']['x']['1']['counts']
    assert n15['only0']==70*y6['only0']==420 and n15['only1']==420
    print(json.dumps({'verifier':'independent exhaustive bitmask/source-clause','checks':tests,'families':{name:d['families'][name]['models'] for name in families},'status':'PASS'},sort_keys=True))
if __name__=='__main__':main()
