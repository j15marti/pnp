 assert tree(cert['terminal_tree'])==17
 # Global complement preserves every native signed edge, E equality and exact-two B relation;
 # fixing one port to 0 cannot discard all witnesses of a feasible instance.
 return {'checked':True,'root':'UNSAT','nodes':17,'chart_variables':len(vs),'remaining_variables':len({abs(l) for c in E for l in c})}
