 for a,b,s in G['edges']:
  assert 0<=a<n and 0<=b<n and s in (0,1) and a//4!=b//4 and a not in ports and b not in ports
  key=tuple(sorted((a//4,b//4)));assert key not in seen;seen.add(key);ports.update((a,b));edge(a,b,s)
 assert len(ports)==n
 for v,t in enumerate(G['types']):
  assert t in ('E','B')
