     const walsh=v=>{for(let s=1;s<L;s*=2)for(let i=0;i<L;i+=2*s)for(let j=0;j<s;j++){let a=v[i+j],b=v[i+j+s];v[i+j]=a+b;v[i+j+s]=a-b}return v};
     walsh(coef);coef=coef.map(x=>x<0n?-x:x);walsh(coef);
